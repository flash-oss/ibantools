/* Carries the registry values in script/iban_spec.js into src/ibantools.ts.
 *
 * src/ibantools.ts is updated in place, not regenerated: it also holds national checks, countries the registry lacks
 * and fixes to registry values. A fixed value carries a comment starting with MARKER on the line above it, so this
 * never changes it. A value that differs from the registry without that comment is only reported, or replaced
 * with `--overwrite`.
 * Run with `npm run update-src` (or `-- --dry-run` for the report only) after `npm run update-registry`,
 * then review `git diff src/`. */

import { readFileSync, writeFileSync } from 'node:fs';
import { autogeneratedCountrySpecs } from './iban_spec.js';

const SRC = new URL('../src/ibantools.ts', import.meta.url);
const MARKER = '// Not from the IBAN registry:';
// The order builder.js writes fields in, so a field added by hand and one added here end up in the same place.
const FIELD_ORDER = [
  'chars',
  'bban_regexp',
  'IBANRegistry',
  'SEPA',
  'branch_indentifier',
  'bank_identifier',
  'account_indentifier',
];
// A country entry: quoted strings and comments may hold braces, so they are skipped whole.
const ENTRY = /\n {2}([A-Z]{2}): \{((?:'[^']*'|\/\/[^\n]*|[^'{}])*)\}/g;
const FIELD = /(\w+): ('[^']*'|[^,\n}]+)/g;

const dryRun = process.argv.includes('--dry-run');
const overwrite = process.argv.includes('--overwrite');
const report = { added: [], overwritten: [], kept: [], markerNotNeeded: [], unexplained: [], skipped: [] };
const seen = new Set();

const source = readFileSync(SRC, 'utf8').replace(ENTRY, (entry, code, body) => {
  const spec = autogeneratedCountrySpecs[code];
  if (!spec) return entry;
  seen.add(code);
  const fields = parseFields(body);
  let changed = false;
  for (const name of FIELD_ORDER) {
    if (spec[name] === undefined) continue;
    // e.g. TR's registry example has no domestic account number, which builds an empty '0-0' range.
    if (name.endsWith('dentifier') && isEmptyRange(spec[name])) {
      report.skipped.push(`${code} ${name}: '${spec[name]}' is an empty range`);
      continue;
    }
    const registry = registryValue(spec, name);
    const field = fields.find((candidate) => candidate.name === name);
    // src/ibantools.ts leaves SEPA out when it is false.
    if (!field && name === 'SEPA' && registry === 'false') continue;
    if (!field) {
      insertInOrder(fields, { name, value: registry, comments: [] });
      report.added.push(`${code} ${name}: ${registry}`);
      changed = true;
      continue;
    }
    const marked = field.comments.some((comment) => comment.startsWith(MARKER));
    if (sameValue(name, field.value, registry, spec.length)) {
      if (marked) report.markerNotNeeded.push(`${code} ${name}: ${field.value}`);
    } else if (marked) {
      report.kept.push(`${code} ${name}: ${field.value}, registry ${registry}`);
    } else if (overwrite) {
      report.overwritten.push(`${code} ${name}: ${field.value} -> ${registry}`);
      field.value = registry;
      changed = true;
    } else {
      report.unexplained.push(`${code} ${name}: src ${field.value}, registry ${registry}`);
    }
  }
  return changed ? formatEntry(code, fields) : entry;
});
for (const code of Object.keys(autogeneratedCountrySpecs).filter((code) => !seen.has(code))) {
  report.skipped.push(`${code}: no entry in src/ibantools.ts to update`);
}

print('Added', report.added);
if (overwrite) print('Overwritten', report.overwritten);
print(`Kept, marked "${MARKER}"`, report.kept);
print('Marked, but the registry now agrees, so the comment can go', report.markerNotNeeded);
if (!overwrite) print('Differ without a marker (mark them, or run with --overwrite)', report.unexplained);
print('Skipped', report.skipped);
if (dryRun) console.log('Dry run: src/ibantools.ts not changed.');
else if (report.added.length || report.overwritten.length) writeFileSync(SRC, source);

// Each field with the comment lines right above it, which belong to it.
function parseFields(body) {
  const fields = [];
  let comments = [];
  for (const line of body.split('\n').map((text) => text.trim())) {
    if (line.startsWith('//')) {
      comments.push(line);
      continue;
    }
    for (const [, name, value] of line.matchAll(FIELD)) {
      fields.push({ name, value: value.trim(), comments });
      comments = [];
    }
  }
  return fields;
}

function formatEntry(code, fields) {
  const lines = fields.flatMap(({ name, value, comments }) => [
    ...comments.map((comment) => `    ${comment}\n`),
    `    ${name}: ${value},\n`,
  ]);
  return `\n  ${code}: {\n${lines.join('')}  }`;
}

// As src/ibantools.ts writes it, e.g. a merged regexp like [0-9]{8} for [0-9]{4}[0-9]{4}.
function registryValue(spec, name) {
  const value = spec[name];
  if (name === 'bban_regexp') return `'${mergeGroups(value)}'`;
  return typeof value === 'string' ? `'${value}'` : String(value);
}

function sameValue(name, current, registry, chars) {
  if (name === 'bban_regexp') return mergeGroups(current.slice(1, -1)) === mergeGroups(registry.slice(1, -1));
  if (name === 'account_indentifier') return readEnd(current, chars) === readEnd(registry, chars);
  return current === registry;
}

// An account at the end of the IBAN reads the same up to any end past it, e.g. '12-28' and '12-27' in a 28-character IBAN.
function readEnd(range, chars) {
  const [start, end] = range.slice(1, -1).split('-').map(Number);
  return `${start}-${Math.min(end, chars - 1)}`;
}

function mergeGroups(regexp) {
  const groups = [];
  for (const [, range, count] of regexp.matchAll(/(\[[^\]]+\])\{(\d+)\}/g)) {
    const last = groups.at(-1);
    if (last?.range === range) last.count += Number(count);
    else groups.push({ range, count: Number(count) });
  }
  return `^${groups.map(({ range, count }) => `${range}{${count}}`).join('')}$`;
}

function isEmptyRange(range) {
  const [start, end] = range.split('-').map(Number);
  return !(end > start);
}

// Before the first field that comes after it in FIELD_ORDER, otherwise last.
function insertInOrder(fields, addition) {
  const rank = (name) => FIELD_ORDER.indexOf(name);
  const index = fields.findIndex(({ name }) => rank(name) > rank(addition.name));
  if (index < 0) fields.push(addition);
  else fields.splice(index, 0, addition);
}

function print(title, lines) {
  console.log(`${title}: ${lines.length ? '\n  ' + lines.join('\n  ') : 'none'}`);
}
