/* Builds script/iban_spec.js from the SWIFT IBAN registry.
 *
 * Download: https://www.swift.com/swift-resource/11971/download
 * or whatever the file path is on this page:
 * https://www.swift.com/standards/data-standards/iban-international-bank-account-number
 * and save it as `script/registry.txt` with `npm run update-registry -- <downloaded file>`,
 * or run `npm run build-spec` to rebuild from the current one, and `git diff script/iban_spec.js` to see changes. */

import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { parse } from 'lil-csv';

export const REGISTRY = new URL('./registry.txt', import.meta.url);
const SPEC = new URL('./iban_spec.js', import.meta.url);

// Registry rows are fields and its columns countries, so each row fills one field of every country.
export const ROW_FIELDS = {
  'Name of country': ['country_name', (value) => value],
  'IBAN prefix country code (ISO 3166)': ['code', (value) => value],
  'SEPA country': ['sepa', (value) => value === 'Yes'],
  'IBAN length': ['length', (value) => parseInt(value, 10) || 0],
  'BBAN structure': ['bban_regexp', buildRegexp],
  'Bank identifier position within the BBAN': ['bank_identifier', fixRanges],
  'Branch identifier position within the BBAN': ['branch_indentifier', fixRanges],
  'IBAN electronic format example': ['iban_example', (value) => value],
  'Domestic account number example': ['account_example', (value) => value.replaceAll(' ', '')],
};

// Parsed as TSV because a quoted cell can span lines (SI's bank identifier position does)
export function readRows(text) {
  return parse(text, { header: false, delimiter: '\t' }).map((row) => row.map((cell) => String(cell ?? '').trim()));
}

export function extract(text) {
  const specs = [];
  for (const [label, ...values] of readRows(text)) {
    const field = ROW_FIELDS[label];
    if (!field) continue;
    const [name, convert] = field;
    values.forEach((value, index) => {
      specs[index] ||= {};
      specs[index][name] = convert(value);
    });
  }
  return specs.map(findAccountPosition);
}

function findAccountPosition(spec) {
  const position = spec.iban_example.indexOf(spec.account_example);
  // Inclusive, like every range ibantools reads: extractIBAN() slices up to and including the end position.
  // e.g. TR's registry example has no domestic account number, so there is no range to find.
  if (spec.account_example && position >= 0)
    spec.account_indentifier = `${position}-${position + spec.account_example.length - 1}`;
  return spec;
}

// The registry counts BBAN positions from 1, ibantools from 0.
function fixRanges(ranges) {
  if (ranges === 'N/A' || ranges === '') return undefined;
  return ranges
    .split('-')
    .map((position) => (parseInt(position, 10) || 0) - 1)
    .join('-');
}

function typeToRange(type) {
  if (type === 'c') return '[A-Z0-9]';
  if (type === 'n') return '[0-9]';
  return '[A-Z]';
}

// e.g. "4!n4!n12!c" becomes "^[0-9]{4}[0-9]{4}[A-Z0-9]{12}$"
function buildRegexp(format) {
  const parts = [...format.matchAll(/([0-9]+)!(.)/g)].map(([, amount, type]) => `${typeToRange(type)}{${amount}}`);
  return `^${parts.join('')}$`;
}

export function createSpecification(specs) {
  const lines = [
    '/*!',
    ' * @license',
    ' * This Source Code Form is subject to the terms of the Mozilla Public',
    ' * License, v. 2.0. If a copy of the MPL was not distributed with this',
    ' * file, You can obtain one at http://mozilla.org/MPL/2.0/. */',
    '',
    'export const autogeneratedCountrySpecs = {',
  ];
  for (const spec of specs) {
    lines.push(`  ${spec.code}: {`);
    lines.push(`    chars: ${spec.length},`);
    lines.push(`    bban_regexp: '${spec.bban_regexp}',`);
    lines.push('    IBANRegistry: true,');
    lines.push(`    SEPA: ${spec.sepa},`);
    if (spec.branch_indentifier) lines.push(`    branch_indentifier: '${spec.branch_indentifier}',`);
    if (spec.bank_identifier) lines.push(`    bank_identifier: '${spec.bank_identifier}',`);
    if (spec.account_indentifier) lines.push(`    account_indentifier: '${spec.account_indentifier}',`);
    lines.push('  },');
  }
  lines.push('};');
  writeFileSync(SPEC, lines.join('\n') + '\n');
}

export function buildSpec() {
  createSpecification(extract(readFileSync(REGISTRY, 'latin1')));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) buildSpec();
